'Medida NO aditiva: precio unitario del insumo en la línea.';
COMMENT ON COLUMN dw.fact_compras.descuento IS
'Medida aditiva: descuento de la línea.';
COMMENT ON COLUMN dw.fact_compras.subtotal IS
'Medida aditiva: subtotal de la línea (cantidad*precio - descuento en la fuente).';
COMMENT ON COLUMN dw.fact_compras.impuesto IS
'Medida aditiva: impuesto PRORRATEADO a la línea en el ETL (no repetir impuesto de cabecera).';
COMMENT ON COLUMN dw.fact_compras.total IS
'Medida aditiva: total de línea = subtotal + impuesto prorrateado (calculado en ETL).';
COMMENT ON COLUMN dw.fact_compras.cantidad_recibida IS
'Medida complementaria: cantidad recibida agregada por detalle de OC.';
COMMENT ON COLUMN dw.fact_compras.cantidad_rechazada IS
'Medida complementaria: cantidad rechazada agregada por detalle de OC.';
COMMENT ON COLUMN dw.fact_compras.cantidad_lineas IS
'Medida constante igual a 1 para facilitar conteos de líneas.';
