-- ============================================================
-- 6. REGLAS DE DISEÑO
-- ============================================================

-- Antes de implementar una dimensión, confirmar:
--
--   1. Grano:
--      ¿Qué representa exactamente una fila?
--
--   2. Business key:
--      ¿Cuál es la clave empresarial estable?
--
--   3. Fuente autoritativa:
--      ¿Qué sistema define oficialmente sus atributos?
--
--   4. Homologación:
--      ¿La fuente comparte la business key empresarial o
--      requiere mapping explícito?
--
--   5. Historia:
--      ¿SCD Tipo 1, Tipo 2 u otra estrategia?
--
--   6. Miembro desconocido:
--      Debe utilizar nombre_dimension_key = 0 cuando aplique.
--
--   7. Integridad:
--      Definir PK, FK, UNIQUE y CHECK necesarios.
--
--   8. Índices:
--      Crear sólo los que aporten integridad o rendimiento.
--
--   9. Pruebas:
--      Incorporar o ampliar tests estructurales.
--
--  10. Instalación:
--      Integrar el nuevo script en el instalador correspondiente
--      y validar su ejecución real en PostgreSQL.
--
--  11. ETL:
--      No utilizar IDs locales de fuentes como claves
--      transversales del Data Warehouse.
--
--  12. Revisión:
--      Los casos no resolubles de manera determinística deben
--      enviarse a revisión y no homologarse por aproximación.
